// Traces the logo's mark (brand/orbit-logo.png) into SVG paths for components/orbit-mark-paths.ts:
// the blue ring and the marigold flame, each separated by color and traced with potrace. The sun
// is a true circle, so it's measured rather than traced. Rerun after the logo changes:
//   node scripts/trace-logo.mjs
import { writeFileSync } from "node:fs";
import potrace from "potrace";
import sharp from "sharp";

const SOURCE = "brand/orbit-logo.png";
const OUT = "components/orbit-mark-paths.ts";
const MARK_BOTTOM = 760; // the wordmark starts below this

const { data, info } = await sharp(SOURCE).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const { width, height } = info;
const at = (x, y) => {
  const i = (y * width + x) * 3;
  return [data[i], data[i + 1], data[i + 2]];
};

// How strongly a pixel is ring blue / sun marigold, 0..1, so traced edges follow the antialiasing.
const blueness = ([r, , b]) => Math.max(0, Math.min(1, (b - r - 40) / 120));
const sunness = ([r, g, b]) => Math.max(0, Math.min(1, (r - b - 60) / 110)) * (g > 110 ? 1 : 0);

// One layer as a grayscale image: black where the color is, white elsewhere.
async function layer(weight, keep) {
  const out = Buffer.alloc(width * height, 255);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      if (!keep(x, y)) continue;
      out[y * width + x] = Math.round(255 * (1 - weight(at(x, y))));
    }
  }
  return sharp(out, { raw: { width, height, channels: 1 } }).png().toBuffer();
}

function trace(png) {
  return new Promise((resolve, reject) => {
    const p = new potrace.Potrace({ threshold: 128, turdSize: 40, optTolerance: 0.2, turnPolicy: potrace.Potrace.TURNPOLICY_MINORITY });
    p.loadImage(png, (err) => {
      if (err) return reject(err);
      const d = /\sd="([^"]+)"/.exec(p.getPathTag())?.[1];
      if (!d) return reject(new Error("nothing traced"));
      resolve(d.replace(/\s+/g, " ").trim());
    });
  });
}

// The flame is the marigold up and to the right of the ring; the sun is the marigold in the middle.
const ringD = await trace(await layer(blueness, (_, y) => y < MARK_BOTTOM));
const flameD = await trace(await layer(sunness, (x, y) => y < 420 && x > 690));

// The ring's middle, and its centerline radius, from its outer and inner edges on the row through
// the middle; the sun's center and radius from its extent.
let ring = { x0: width, x1: 0, y0: height, y1: 0 };
let sun = { x0: width, x1: 0, y0: height, y1: 0 };
let flame = { x0: width, x1: 0, y0: height, y1: 0 };
const grow = (box, x, y) => {
  box.x0 = Math.min(box.x0, x);
  box.x1 = Math.max(box.x1, x);
  box.y0 = Math.min(box.y0, y);
  box.y1 = Math.max(box.y1, y);
};
for (let y = 0; y < MARK_BOTTOM; y++) {
  for (let x = 0; x < width; x++) {
    const p = at(x, y);
    if (blueness(p) > 0.5) grow(ring, x, y);
    if (sunness(p) > 0.5) grow(y < 420 && x > 690 ? flame : sun, x, y);
  }
}
const cx = (ring.x0 + ring.x1) / 2;
const cy = (ring.y0 + ring.y1) / 2;
let inner = cx;
while (inner > ring.x0 && blueness(at(Math.round(inner), Math.round(cy))) < 0.5) inner--;
const outerR = cx - ring.x0;
const innerR = cx - inner;
const round = (n) => Math.round(n * 10) / 10;

const file = `// Generated by scripts/trace-logo.mjs from brand/orbit-logo.png. Don't edit by hand; rerun the
// script after changing the logo. Paths are in the logo image's own pixels.

export const LOGO_RING = { cx: ${round(cx)}, cy: ${round(cy)}, r: ${round((outerR + innerR) / 2)}, width: ${round(outerR - innerR)} };
export const LOGO_SUN = { cx: ${round((sun.x0 + sun.x1) / 2)}, cy: ${round((sun.y0 + sun.y1) / 2)}, r: ${round((sun.x1 - sun.x0) / 2)} };
export const LOGO_FLAME_BOX = { x0: ${flame.x0}, y0: ${flame.y0}, x1: ${flame.x1}, y1: ${flame.y1} };

export const LOGO_RING_D = "${ringD}";

// The flame with its inner tongue cut through (even-odd fill).
export const LOGO_FLAME_D = "${flameD}";
`;
writeFileSync(OUT, file);
console.log(`wrote ${OUT}`, { ring: { cx, cy, outerR, innerR }, sun, flame, ringLen: ringD.length, flameLen: flameD.length });
